    const transform = () => page.locator(".agent-track").first().evaluate((el) => getComputedStyle(el).transform);
    const before = await transform(); await page.waitForTimeout(500); assert.notEqual(await transform(), before);
    await page.getByRole("button", { name: "Pause animation", exact: true }).click();
    await page.waitForFunction(() => getComputedStyle(document.querySelector(".agent-track")).animationPlayState === "paused");
    await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    const paused = await transform(); await page.waitForTimeout(400); assert.equal(await transform(), paused);
    await page.locator(".agent-showcase").screenshot({ path: `${output}/agents-animation.png` });
    await page.getByRole("button", { name: "Play animation", exact: true }).click();
    await page.mouse.move(1, 1); await page.waitForTimeout(300); assert.notEqual(await transform(), paused);
    await page.locator("#hero-title").scrollIntoViewIfNeeded();
    await page.waitForFunction(() => document.querySelector(".agent-showcase").dataset.paused === "true");
    assert.deepEqual(errors, []);
    await writeFile(`${output}/results.json`, JSON.stringify({ journeys: "passed", results, errors }, null, 2));
    console.log(JSON.stringify({ journeys: "passed", results, errors }));
