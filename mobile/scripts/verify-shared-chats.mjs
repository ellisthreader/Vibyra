import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { sharedChatProbe } from './shared-chat-probe.mjs';
import { serveFixture } from './fixture-server.mjs';
import { until, capture } from './ui-test-helpers.mjs';
import { randomUUID } from 'node:crypto';
const probe = await sharedChatProbe();
let served, browser;
try {
  served = await serveFixture('tests/terminalHostFixture.tsx');
  browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${served.url}/?existing=1&conversation=1&invitation=${encodeURIComponent(JSON.stringify(probe.pairing))}`);
  const input = page.getByRole('textbox');
  await input.waitFor({ timeout: 30000 }).catch(async e => { console.error(await page.locator('body').innerText(), errors); throw e; });
  await input.fill('Reply with exactly: Shared iPhone message verified. Do not use tools or inspect files.');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  const snapshot = () => probe.local('conversation.snapshot', { sessionId: probe.session.id });
  await until(async () => (await snapshot()).turnState === 'completed', 'real phone prompt completion', 90000);
  const first = await snapshot();
  assert.ok(first.items.some(i => i.role === 'assistant' && i.text.includes('Shared iPhone message verified')));
  await page.getByText('Shared iPhone message verified.', { exact: true }).waitFor();
  console.log('PASS phone composer -> encrypted Desktop backend -> real Codex -> same Desktop snapshot');
  await input.fill('Keep this unsent draft');
  probe.typing(false);
  await page.getByText('Typing from your phone is off.', { exact: false }).waitFor();
  assert.equal(await input.inputValue(), 'Keep this unsent draft');
  assert.equal(await page.getByRole('button', { name: 'Send message', exact: true }).getAttribute('aria-disabled'), 'true');
  probe.typing(true);
  await until(async () => await page.getByRole('button', { name: 'Send message', exact: true }).getAttribute('aria-disabled') !== 'true', 'typing switch enabled');
  const submissionId = randomUUID();
  const params = { sessionId: probe.session.id, submissionId, text: 'Reply with exactly: Desktop message verified. Do not use tools or inspect files.' };
  await probe.local('turn.submit', params);
  await until(async () => (await snapshot()).turnState === 'completed', 'real Desktop completion', 90000);
  await page.getByText('Desktop message verified.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Take control', exact: true }).waitFor();
  assert.equal(await input.inputValue(), 'Keep this unsent draft');
  const duplicate = await probe.local('turn.submit', params);
  assert.equal(duplicate.status, 'accepted');
  assert.equal((await snapshot()).items.filter(i => i.id === submissionId).length, 1);
  await page.evaluate(async () => {
    const store = window.sharedChatFixture;
    await store.actions.reconnect();
  });
  await page.getByText('Desktop message verified.', { exact: true }).waitFor();
  assert.equal(await input.inputValue(), 'Keep this unsent draft');
  assert.equal((await snapshot()).items.filter(i => i.id === submissionId).length, 1);
  console.log('PASS authenticated reconnect keeps the same chat and draft with no replay');
  console.log('PASS Desktop sends to same phone chat, duplicate receipt, controller handoff, typing gate, draft preservation');
  if (await page.getByRole('button', { name: 'Take control', exact: true }).count()) await page.getByRole('button', { name: 'Take control', exact: true }).click();
  await input.fill('Use vibyra_ask_user now. Ask which color to choose, with options Blue and Green. Wait for my answer, then reply with only the chosen color. Do not use other tools.');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await until(async () => (await snapshot()).items.some(i => i.kind === 'question' && i.status === 'pending'), 'real question tool', 90000);
  await capture(page, '/tmp/vibyra-shared-phone-question.png');
  const question = (await snapshot()).items.find(i => i.kind === 'question' && i.status === 'pending');
  await probe.local('question.answer', { sessionId: probe.session.id, turnId: question.turnId, requestId: question.requestId,
    actionVersion: question.actionVersion, decisionId: randomUUID(), answers: { [question.questions[0].id]: { answers: ['Blue'] } } });
  await until(async () => (await snapshot()).turnState === 'completed', 'real question acknowledgement', 90000);
  assert.equal((await snapshot()).items.find(i => i.id === question.id).status, 'accepted');
  console.log('PASS real question contract and Desktop response reflected on phone');
  await capture(page, '/tmp/vibyra-shared-phone-dark.png');
  assert.deepEqual(errors, []);
  console.log(`PASS shared chats. Isolated project: ${probe.dir}`);
} finally { await browser?.close(); served?.close(); await probe.close(); }
